"""Regenerate results/*.csv and results/tables.md (a few seconds).

    cd solvers/harmonic_model && python3 examples/make_tables.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)

import numpy as np  # noqa: E402
from harmonic_model import model_a as A, model_b as B, twobody as T  # noqa: E402
from harmonic_model.__main__ import main  # noqa: E402

MASSES = [0.1, 1, 10, 100, 1836]
OUT = os.path.join(ROOT, "results")
os.makedirs(OUT, exist_ok=True)

main(["--model", "A", "-o", os.path.join(OUT, "model_A_k1_kp0.csv"), "--masses", *map(str, MASSES)])
main(["--model", "B", "--g", "1", "-o", os.path.join(OUT, "model_B_g1_k1.csv"), "--masses", *map(str, MASSES)])
main(["--model", "twobody", "-o", os.path.join(OUT, "twobody.csv"), "--masses", *map(str, MASSES)])
dense = list(np.geomspace(1e-2, 1e5, 57))
main(["--model", "B", "--g", "1", "-o", os.path.join(OUT, "model_B_g1_dense.csv"), "--masses", *map(str, dense)])
main(["--model", "A", "-o", os.path.join(OUT, "model_A_dense.csv"), "--masses", *map(str, dense)])


def f(x, n=5):
    return f"{x:.{n}g}"


L = []
L.append("# Tables (k = 1, k' = 0; Model B g = 1). Generated by examples/make_tables.py\n")
L.append("## Model A\n")
L.append("| M | E | dE/dlnM | d2E/dlnM2 | <R> | eta | sigma2_cm | sigma2_mid | chi_fixed | chi_inv | S_vN(R|s) | S_vN(x1|x2) | S_vN(x1|x3) |")
L.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
for M in MASSES:
    d = A.summary(M)
    L.append("| " + " | ".join(f(float(d[k])) for k in ("M", "E", "dE_dlnM", "d2E_dlnM2", "R_mean", "eta", "sig2_cm",
                                                         "sig2_mid", "chi_fixed", "chi_inv", "SvN_R_s", "SvN_x1_x2",
                                                         "SvN_x1_x3")) + " |")
L.append("\nS_vN(R|rho) = 0 exactly; chi_sep = 0 exactly.\n")
L.append("## Model B (g = 1)\n")
L.append("| M | lam | E | dE/dlnM | d2E/dlnM2 | <R> | R_peak | eta | CM curv. | CM shell | chi_fixed | chi_inv | chi_sep | S_L(R|s) | S_vN(R|s) | E(J=1)-E(J=0) | <1/R^2>/M |")
L.append("|" + "---|" * 17)
for M in MASSES:
    d = B.summary(M, 1.0)
    L.append("| " + " | ".join(f(d[k]) for k in ("M", "lam", "E", "dE_dlnM", "d2E_dlnM2", "R_mean", "R_peak", "eta",
                                                 "cm_curv", "cm_shell", "chi_fixed", "chi_inv", "chi_sep",
                                                 "SL_R_s", "SvN_R_s", "E10_minus_E00", "B_from_invR2")) + " |")
L.append(f"\nR_e = (4g/K)^(1/4) = {f(B.bond_length(1.0), 8)}; M_c(CM, g=1) = {f(B.critical_mass_cm(1.0), 10)}.")
lim = B.entanglement_R_s_large_M(1.0)
L.append(f"M -> inf limit of R|s: S_vN = {f(lim['S_vN'], 8)}, S_L = {f(lim['S_L'], 8)}.\n")
L.append("## M_c of the CM-referenced density versus g (k = 1)\n")
L.append("| g | M_c | lam(M_c) | eta(M_c) |")
L.append("|---|---|---|---|")
for g in (0.01, 0.1, 1.0, 10.0, 100.0):
    Mc = B.critical_mass_cm(g)
    L.append(f"| {g} | {f(Mc, 8)} | {f(float(B.params(Mc, g)['lam']), 6)} | {f(float(B.pair_moments(Mc, g)['eta']), 6)} |")
L.append("\n## Two-body\n")
L.append("| M | chi harmonic = 3/(32(M+1)^2) | chi Coulomb = (3/4)/(M+1)^2 | chi_inv |")
L.append("|---|---|---|---|")
for M in MASSES:
    L.append(f"| {M} | {f(float(T.harmonic_chi_fixed(M)))} | {f(float(T.coulomb_chi_fixed(M)))} | 0 |")
with open(os.path.join(OUT, "tables.md"), "w") as fh:
    fh.write("\n".join(L) + "\n")
print("\n".join(L))
